  /// Returns a closed polygon for [poi], or null to use the generic outline.
  static List<({double lat, double lng})>? polygonFor(POI poi) {
    final names = <String>{poi.name};
    if (poi.names != null) {
      names.addAll(poi.names!.values);
    }

    for (final name in names) {
      final canonical = canonicalEnglishNameFor(name) ?? name;
      final ring = _byCanonicalName[canonical];
      if (ring != null) {
        final polygon = ring
            .map((p) => (lat: p[1], lng: p[0]))
            .toList(growable: false);
        final distanceM = _centroidDistanceMeters(poi, polygon);
        if (distanceM > _maxCentroidDistanceM) {
          debugPrint(
            'PoiOutlineCatalog: ignoring misaligned outline for '
            '$canonical (${distanceM.toStringAsFixed(0)}m from POI)',
          );
          return null;
        }
        return polygon;
      }
    }
    return null;
  }

  static double _centroidDistanceMeters(
    POI poi,
    List<({double lat, double lng})> ring,
  ) {
    final lat = poi.lat;
    final lng = poi.lng;
    if (lat == null || lng == null || ring.isEmpty) return 0;

    final centroidLat = ring.fold(0.0, (sum, p) => sum + p.lat) / ring.length;
    final centroidLng = ring.fold(0.0, (sum, p) => sum + p.lng) / ring.length;
    return _distanceMeters(lat, lng, centroidLat, centroidLng);
  }

  static double _distanceMeters(
    double lat1,
    double lng1,
    double lat2,
    double lng2,
  ) {
    const earthRadiusM = 6378137.0;
    final dLat = (lat2 - lat1) * math.pi / 180;
    final dLng = (lng2 - lng1) * math.pi / 180;
    final lat1Rad = lat1 * math.pi / 180;
    final lat2Rad = lat2 * math.pi / 180;
    final a = math.sin(dLat / 2) * math.sin(dLat / 2) +
        math.cos(lat1Rad) *
            math.cos(lat2Rad) *
            math.sin(dLng / 2) *
            math.sin(dLng / 2);
    return earthRadiusM * 2 * math.atan2(math.sqrt(a), math.sqrt(1 - a));
  }
